#!/usr/bin/env node
/**
 * Build the Pascal engine bundle.
 *
 *   engine/parse.jison  --jison-->  parse.js
 *   engine/*.js, engine/units/*.js, engine/llvm.js/*.js + engine/host.js
 *                       ------->    src/engine/generated/engine.bundle.js
 *
 * The bundle is a single classic script that defines `PascalEngine` in the
 * global scope it is evaluated in (see engine/host.js).
 */

import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const engineDir = join(root, 'engine');
const outFile = join(root, 'src', 'engine', 'generated', 'engine.bundle.js');
const jisonBin = join(root, 'node_modules', 'jison', 'lib', 'cli.js');

function read(path) {
    return readFileSync(path, 'utf8');
}

function newestMtime(paths) {
    return Math.max(...paths.map((p) => statSync(p).mtimeMs));
}

function listFiles(dir) {
    return readdirSync(dir)
        .filter((name) => name.endsWith('.js'))
        .map((name) => join(dir, name));
}

const grammarFile = join(engineDir, 'parse.jison');
const moduleFiles = {
    ir: join(engineDir, 'ir.js'),
    ieee754: join(engineDir, 'ieee754.js'),
};
for (const file of listFiles(join(engineDir, 'units'))) {
    moduleFiles[`units/${file.split('/').pop().replace(/\.js$/, '')}`] = file;
}
const llvmFiles = listFiles(join(engineDir, 'llvm.js'));
const hostFile = join(engineDir, 'host.js');

// Skip the build when the bundle is newer than every input (keeps dev start fast).
try {
    const inputs = [grammarFile, hostFile, ...Object.values(moduleFiles), ...llvmFiles, fileURLToPath(import.meta.url)];
    if (statSync(outFile).mtimeMs > newestMtime(inputs) && !process.argv.includes('--force')) {
        process.exit(0);
    }
} catch {
    // bundle does not exist yet
}

// 1. Generate the parser from the grammar.
const scratch = join(root, 'node_modules', '.cache', 'engine');
mkdirSync(scratch, { recursive: true });
const parserFile = join(scratch, 'parse.js');
execFileSync(process.execPath, [jisonBin, grammarFile, '-o', parserFile], { stdio: ['ignore', 'inherit', 'inherit'] });

// 2. Collect sources.
const modules = { parse: read(parserFile) };
for (const [name, file] of Object.entries(moduleFiles)) {
    modules[name] = read(file);
}
const files = {};
for (const file of llvmFiles) {
    files[`llvm.js/${file.split('/').pop()}`] = read(file);
}

// 3. Assemble the bundle from the host template.
const host = read(hostFile)
    .replace('/*__MODULES__*/ {}', () => JSON.stringify(modules))
    .replace('/*__FILES__*/ {}', () => JSON.stringify(files));

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(
    outFile,
    `// GENERATED by scripts/build-engine.mjs. Do not edit, do not commit.\n${host}`,
);
console.log(`engine bundle written: ${outFile} (${(host.length / 1024).toFixed(0)} kB)`);
